"""Resolve dependencies with pip-tools and attach release hashes from official PyPI metadata.

Fetching release metadata avoids downloading every wheel for every target platform.
Installation still verifies the actual downloaded distribution with --require-hashes.
"""

import argparse
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parents[1]
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;]+)(?:\s*;\s*(.+))?$")


def release_hashes(package):
    name, version = package
    response = requests.get(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60)
    response.raise_for_status()
    hashes = sorted({item["digests"]["sha256"] for item in response.json()["urls"]})
    if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", value) for value in hashes):
        raise ValueError(f"Invalid or missing PyPI hashes: {name}=={version}")
    return package, hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-resolved", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    resolved = {}
    with tempfile.TemporaryDirectory() as directory:
        for stem in ("requirements", "requirements-dev"):
            source = ROOT / (stem + ".lock")
            if not args.from_resolved:
                source = Path(directory) / (stem + ".lock")
                subprocess.run(
                    [
                        sys.executable,
                        "-m",
                        "piptools",
                        "compile",
                        "--allow-unsafe",
                        "--no-emit-index-url",
                        "--output-file",
                        str(source),
                        stem + ".in",
                    ],
                    cwd=ROOT,
                    check=True,
                    stdout=subprocess.DEVNULL,
                )
            entries = []
            for line in source.read_text(encoding="utf-8").splitlines():
                match = PIN.fullmatch(line.strip().removesuffix("\\").strip())
                if match:
                    entries.append(match.groups())
                elif line and not line.startswith(("#", " ", "\t")):
                    raise ValueError(f"Unsupported resolved requirement: {line}")
            if not entries:
                raise ValueError(f"Empty dependency resolution: {stem}")
            resolved[stem] = entries
    packages = {(name, version) for entries in resolved.values() for name, version, _ in entries}
    with ThreadPoolExecutor(max_workers=8) as pool:
        hashes = dict(pool.map(release_hashes, sorted(packages)))
    for stem, entries in resolved.items():
        lines = [
            "# Generated by: python tools/lock_dependencies.py",
            "# Resolver: pip-tools; SHA256: official PyPI release metadata, all distributions.",
            "# Install with --require-hashes. Do not edit by hand.",
            "",
        ]
        for name, version, marker in entries:
            lines.append(name + "==" + version + ((" ; " + marker) if marker else "") + " \\")
            values = hashes[name, version]
            lines.extend(
                "    --hash=sha256:" + value + (" \\" if i < len(values) - 1 else "")
                for i, value in enumerate(values)
            )
        (ROOT / (stem + ".lock")).write_text(
            "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
        )
        print(f"{stem}.lock: {len(entries)} pinned dependencies with SHA256")


if __name__ == "__main__":
    main()
